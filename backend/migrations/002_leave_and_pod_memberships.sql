BEGIN;

-- A normal employee can belong to a pod as well as the pod leader already
-- recorded in public.pods.  Historical mappings remain intact by date.
CREATE TABLE IF NOT EXISTS public.employee_pod_memberships (
  employee_pod_membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Emp_id" BIGINT NOT NULL REFERENCES public."Employee"("Emp_id"),
  pod_id BIGINT NOT NULL REFERENCES public.pods(pod_id),
  effective_from DATE NOT NULL DEFAULT DATE '2026-12-01',
  effective_to DATE,
  status VARCHAR(30) NOT NULL DEFAULT 'Active',
  is_primary BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (effective_to IS NULL OR effective_to >= effective_from),
  UNIQUE ("Emp_id", pod_id, effective_from)
);

CREATE INDEX IF NOT EXISTS employee_pod_memberships_lookup_idx
  ON public.employee_pod_memberships ("Emp_id", effective_from, effective_to);

-- Seed only employees whose designation has the same process wording as the
-- existing pod leader.  This uses the current Employee and pods records; it
-- never changes a pod leader or invents a pod name.
INSERT INTO public.employee_pod_memberships
  ("Emp_id", pod_id, effective_from, effective_to, status, is_primary)
SELECT employee."Emp_id", pod.pod_id, DATE '2026-12-01', DATE '2027-12-31', 'Active', TRUE
FROM public."Employee" AS employee
JOIN public.pods AS pod ON TRUE
JOIN public."Employee" AS leader ON leader."Emp_id" = pod.pod_lead_id
WHERE LOWER(COALESCE(employee.emp_status, '')) = 'active'
  AND employee."Emp_id" <> pod.pod_lead_id
  AND (
    (LOWER(employee.designation) LIKE '%customer support%' AND LOWER(leader.designation) LIKE '%customer support%')
    OR (LOWER(employee.designation) LIKE '%order management%' AND LOWER(leader.designation) LIKE '%order management%')
    OR (LOWER(employee.designation) LIKE '%retention%' AND LOWER(leader.designation) LIKE '%retention%')
    OR (LOWER(employee.designation) LIKE '%ndr%' AND LOWER(leader.designation) LIKE '%ndr%')
    OR (LOWER(employee.designation) LIKE '%acc%' AND LOWER(leader.designation) LIKE '%acc%')
  )
ON CONFLICT ("Emp_id", pod_id, effective_from) DO NOTHING;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.employee_pod_memberships TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.employee_pod_memberships_employee_pod_membership_id_seq TO service_role;

COMMIT;

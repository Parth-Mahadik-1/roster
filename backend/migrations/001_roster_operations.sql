CREATE TABLE IF NOT EXISTS public.operating_calendars (
  calendar_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_process_id BIGINT NOT NULL UNIQUE REFERENCES public."Brand_processes"("Brand_process_id"),
  operates_sundays BOOLEAN NOT NULL DEFAULT TRUE,
  observes_public_holidays BOOLEAN NOT NULL DEFAULT FALSE,
  effective_from DATE NOT NULL DEFAULT DATE '2026-12-01',
  effective_to DATE,
  status VARCHAR(30) NOT NULL DEFAULT 'Active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

CREATE TABLE IF NOT EXISTS public.india_holidays (
  holiday_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  holiday_date DATE NOT NULL,
  holiday_name VARCHAR(150) NOT NULL,
  scope VARCHAR(30) NOT NULL DEFAULT 'National',
  state_code VARCHAR(10),
  is_working_override BOOLEAN NOT NULL DEFAULT FALSE,
  source_note VARCHAR(300),
  UNIQUE (holiday_date, holiday_name, scope, state_code)
);

CREATE TABLE IF NOT EXISTS public.employee_weekly_offs (
  weekly_off_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Emp_id" BIGINT NOT NULL REFERENCES public."Employee"("Emp_id"),
  weekday SMALLINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  effective_from DATE NOT NULL DEFAULT DATE '2026-12-01',
  effective_to DATE,
  status VARCHAR(30) NOT NULL DEFAULT 'Active',
  UNIQUE ("Emp_id", effective_from)
);

CREATE TABLE IF NOT EXISTS public.employee_availability (
  availability_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Emp_id" BIGINT NOT NULL REFERENCES public."Employee"("Emp_id"),
  unavailable_from DATE NOT NULL,
  unavailable_to DATE NOT NULL,
  availability_type VARCHAR(30) NOT NULL CHECK (availability_type IN ('Leave', 'Comp Off', 'Unavailable')),
  status VARCHAR(30) NOT NULL DEFAULT 'Approved',
  reason VARCHAR(300),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (unavailable_to >= unavailable_from)
);

CREATE TABLE IF NOT EXISTS public.roster_runs (
  roster_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  roster_year SMALLINT NOT NULL,
  roster_month SMALLINT NOT NULL CHECK (roster_month BETWEEN 1 AND 12),
  status VARCHAR(30) NOT NULL CHECK (status IN ('Generated', 'Validated', 'Infeasible', 'Published')),
  source VARCHAR(30) NOT NULL DEFAULT 'CP-SAT',
  diagnostics JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.generated_roster_assignments (
  generated_assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  roster_run_id BIGINT NOT NULL REFERENCES public.roster_runs(roster_run_id) ON DELETE CASCADE,
  roster_date DATE NOT NULL,
  "Emp_id" BIGINT NOT NULL REFERENCES public."Employee"("Emp_id"),
  brand_process_id BIGINT NOT NULL REFERENCES public."Brand_processes"("Brand_process_id"),
  shift_id BIGINT NOT NULL REFERENCES public.shifts(shift_id),
  assignment_status VARCHAR(30) NOT NULL DEFAULT 'Scheduled',
  assignment_source VARCHAR(30) NOT NULL DEFAULT 'Optimized',
  UNIQUE (roster_run_id, roster_date, "Emp_id"),
  UNIQUE (roster_run_id, roster_date, brand_process_id, shift_id, "Emp_id")
);

CREATE INDEX IF NOT EXISTS employee_availability_date_idx ON public.employee_availability (unavailable_from, unavailable_to);
CREATE INDEX IF NOT EXISTS generated_roster_date_idx ON public.generated_roster_assignments (roster_run_id, roster_date);


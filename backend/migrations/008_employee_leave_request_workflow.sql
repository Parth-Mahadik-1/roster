BEGIN;

-- Employee-submitted requests stay Pending here until a manager decides.
-- employee_availability is intentionally reserved for Approved requests only.
CREATE TABLE IF NOT EXISTS public.employee_leave_requests (
  leave_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Emp_id" BIGINT NOT NULL REFERENCES public."Employee"("Emp_id"),
  unavailable_from DATE NOT NULL,
  unavailable_to DATE NOT NULL,
  request_type VARCHAR(30) NOT NULL CHECK (request_type IN ('Leave', 'Comp Off', 'Unavailable')),
  status VARCHAR(30) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Cancelled')),
  review_note VARCHAR(300),
  availability_id BIGINT REFERENCES public.employee_availability(availability_id),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ,
  CHECK (unavailable_to >= unavailable_from),
  CHECK (request_type <> 'Unavailable' OR unavailable_from = unavailable_to)
);

CREATE INDEX IF NOT EXISTS employee_leave_requests_status_idx
  ON public.employee_leave_requests (status, unavailable_from, unavailable_to);
CREATE INDEX IF NOT EXISTS employee_leave_requests_employee_idx
  ON public.employee_leave_requests ("Emp_id", unavailable_from, unavailable_to);

CREATE OR REPLACE FUNCTION public.set_leave_request_reviewed_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status IN ('Approved', 'Rejected', 'Cancelled') AND OLD.status = 'Pending' THEN
    NEW.reviewed_at := NOW();
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS employee_leave_requests_reviewed_at ON public.employee_leave_requests;
CREATE TRIGGER employee_leave_requests_reviewed_at
BEFORE UPDATE OF status ON public.employee_leave_requests
FOR EACH ROW EXECUTE FUNCTION public.set_leave_request_reviewed_at();

GRANT SELECT, INSERT, UPDATE ON public.employee_leave_requests TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.employee_leave_requests_leave_request_id_seq TO service_role;

COMMIT;

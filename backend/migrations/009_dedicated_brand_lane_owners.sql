-- A dedicated owner is defined at the schedulable lane level: brand + process
-- + shift. This avoids assigning one person to incompatible morning/night or
-- multi-process work on the same day.
CREATE TABLE IF NOT EXISTS public.brand_process_shift_owners (
  dedicated_owner_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_process_id BIGINT NOT NULL REFERENCES public."Brand_processes"("Brand_process_id"),
  shift_id BIGINT NOT NULL REFERENCES public.shifts(shift_id),
  "Emp_id" BIGINT NOT NULL REFERENCES public."Employee"("Emp_id"),
  effective_from DATE NOT NULL DEFAULT DATE '2026-12-01',
  effective_to DATE,
  status VARCHAR(30) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (effective_to IS NULL OR effective_to >= effective_from),
  UNIQUE (brand_process_id, shift_id, effective_from)
);

CREATE INDEX IF NOT EXISTS dedicated_owner_lookup_idx
  ON public.brand_process_shift_owners (brand_process_id, shift_id, effective_from, effective_to)
  WHERE status = 'Active';

COMMENT ON TABLE public.brand_process_shift_owners IS
  'Dedicated operational owner for a brand/process/shift lane. The roster uses this employee whenever present; active eligibility backups cover weekly offs, leave and absence.';

GRANT SELECT, INSERT, UPDATE, DELETE ON public.brand_process_shift_owners TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.brand_process_shift_owners_dedicated_owner_id_seq TO service_role;

COMMIT;
